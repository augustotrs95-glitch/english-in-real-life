"""Generate model clips and Flite segment data. Run from the repository root."""
import ctypes as ffi
import json
from pathlib import Path
import subprocess
import tempfile

AUDIO = Path("pronunciation/audio")
MANIFEST = Path("tools/aligned-models.json")
EXAMPLES = ["thin", "tin", "then", "den", "ship", "sheep", "bad", "bed"]
P, S, F = ffi.c_void_p, ffi.c_char_p, ffi.c_float


def bind(library, name, result, *args):
    fn = getattr(library, name)
    fn.restype = result
    fn.argtypes = args
    return fn


def main():
    lib = ffi.CDLL("libflite.so.1")
    voices = ffi.CDLL("libflite_cmu_us_slt.so.1")
    lib.flite_init()
    speaker = bind(voices, "register_cmu_us_slt", P, S)(None)
    synth = bind(lib, "flite_synth_text", P, S, P)
    relation = bind(lib, "utt_relation", P, P, S)
    head = bind(lib, "relation_head", P, P)
    next_item = bind(lib, "item_next", P, P)
    name = bind(lib, "item_feat_string", S, P, S)
    end = bind(lib, "item_feat_float", F, P, S)
    wave = bind(lib, "utt_wave", P, P)
    save = bind(lib, "cst_wave_save_riff", ffi.c_int, P, S)
    delete = bind(lib, "delete_utterance", None, P)

    targets = json.loads(MANIFEST.read_text(encoding="utf-8"))
    timings = {}
    with tempfile.TemporaryDirectory() as directory:
        wav = Path(directory) / "model.wav"
        for word in sorted(set(EXAMPLES) | {word for word, _ in targets.values()}):
            utterance = synth(word.encode(), speaker)
            try:
                segments = []
                item = head(relation(utterance, b"Segment"))
                while item:
                    segments.append([name(item, b"name").decode(), round(end(item, b"end"), 4)])
                    item = next_item(item)
                timings[word] = segments
                save(wave(utterance), str(wav).encode())
                subprocess.run([
                    "ffmpeg", "-loglevel", "error", "-y", "-i", str(wav),
                    "-map_metadata", "-1", "-codec:a", "libmp3lame", "-q:a", "5",
                    str(AUDIO / f"{word}.mp3"),
                ], check=True)
            finally:
                delete(utterance)

    for ipa, (word, phone) in targets.items():
        if sum(segment == phone for segment, _ in timings[word]) != 1:
            raise ValueError(f"{ipa}: expected exactly one {phone} in {word}")
    data = "// Generated by tools/generate-models.py. Segment end times in seconds.\n"
    for label, values in [("targets", targets), ("segmentsByWord", timings)]:
        entries = ",\n".join(f"  {json.dumps(key, ensure_ascii=False)}: {json.dumps(value)}"
                             for key, value in values.items())
        data += f"export const {label} = {{\n{entries},\n}};\n"
    Path("pronunciation/model-data.mjs").write_text(data, encoding="utf-8")


if __name__ == "__main__":
    main()
